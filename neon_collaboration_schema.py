def inspect_collaboration_sqlite(db):
    """Only source table/column names and counts; no rows or credentials."""
    if not isinstance(db,sqlite3.Connection):
        raise TypeError('Offline SQLite connection required')
    rows=[]
    for name,columns,_ in _COLLAB:
        actual=tuple(row[1] for row in db.execute(
            'PRAGMA table_info("'+name+'")').fetchall())
        if actual!=columns:
            raise ValueError('Collaboration schema requires manual review: '+name)
        count=db.execute('SELECT COUNT(*) FROM "'+name+'"').fetchone()[0]
        rows.append({'table':name,'columns':len(columns),'rows':count})
    return {'status':'collaboration_schema_preview_only',
            'table_count':len(rows),'tables':rows,'postgres_connected':False,
            'data_exported':False,'migration_executed':False,
            'production_ready':False,'publishing_enabled':False}
