"""Parity checks for five additional private collaboration tables."""
import sqlite3
import unittest
from bam_offline_gateway import BAMOfflineGateway
from neon_collaboration_schema import (
    COLLABORATION_NAMES,collaboration_ddl_preview,
    inspect_collaboration_sqlite)
from neon_scoped_collaboration_queries import prepare_pending_owner_invitations


class NeonCollaborationSchemaTests(unittest.TestCase):
    def setUp(self):
        self.db=sqlite3.connect(':memory:')
        self.app=BAMOfflineGateway(self.db,enabled=False,
            trusted_invitation_delivery=lambda *args:None)
    def tearDown(self):
        self.db.close()

    def test_five_table_parity_without_private_row_exposure(self):
        report=inspect_collaboration_sqlite(self.db)
        self.assertEqual(report['table_count'],5)
        self.assertEqual({r['table'] for r in report['tables']},
                         set(COLLABORATION_NAMES))
        self.assertTrue(all(r['rows']==0 for r in report['tables']))
        self.assertFalse(report['postgres_connected'])
        self.assertFalse(report['migration_executed'])
        self.assertFalse(report['data_exported'])
        self.assertFalse(report['production_ready'])
        self.assertFalse(report['publishing_enabled'])

    def test_private_row_values_never_in_parity_report(self):
        self.db.execute("""INSERT INTO bam_business_invitations
            (token_hash,tenant_id,email,role,expires_at,created_by,
             invitation_id,delivery_state)
            VALUES (?,?,?,?,?,?,?,?)""",
            ('d'*64,'shop','guest@private.invalid','viewer',500,
             'actor','a'*32,'delivered'))
        report=inspect_collaboration_sqlite(self.db)
        self.assertEqual(report['tables'][0]['rows'],1)
        self.assertNotIn('guest@private.invalid',str(report))
        self.assertNotIn('d'*64,str(report))
        self.assertNotIn('shop',str(report))

    def test_postgres_ddl_has_identity_and_unique_invitation_id(self):
        ddl=collaboration_ddl_preview()
        self.assertEqual(len(ddl),8)
        self.assertTrue(any('GENERATED BY DEFAULT AS IDENTITY' in s
                            for s in ddl))
        self.assertTrue(any('CREATE UNIQUE INDEX' in s for s in ddl))
        self.assertFalse(any('AUTOINCREMENT' in s for s in ddl))

    def test_new_source_column_is_refused(self):
        self.db.execute('ALTER TABLE bam_review_feedback ADD COLUMN extra TEXT')
        with self.assertRaisesRegex(ValueError,'bam_review_feedback'):
            inspect_collaboration_sqlite(self.db)

    def test_owner_query_never_selects_invite_secret(self):
        sql,params=prepare_pending_owner_invitations(
            tenant_id='shop',verified_subject_id='abc123',server_now=101)
        self.assertEqual(sql.count('%s'),3)
        self.assertEqual(params,('shop',101,'abc123'))
        self.assertNotIn('token_hash',sql)
        self.assertIn("m.role='owner'",sql)
        for values in (
            {'tenant_id':'other;DROP TABLE members'},
            {'verified_subject_id':'abc\nxyz'},
            {'server_now':True},
            {'server_now':-1}):
            settings=dict(tenant_id='shop',verified_subject_id='abc123',
                          server_now=101)
            settings.update(values)
            with self.assertRaises(ValueError):
                prepare_pending_owner_invitations(**settings)

if __name__=='__main__':
    unittest.main()
