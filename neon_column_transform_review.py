"""Conservative, metadata-only SQLite -> PostgreSQL target-column review.

This generates *proposals*, never approved value transformations. It reads no
source records and cannot connect to Postgres, write data or authorize cutover.
A human must independently review every column, including exact type matches.
"""
import hashlib
import json
import re
import sqlite3

from neon_schema_blueprint import _TABLES as _BASE
from neon_collaboration_schema import _COLLAB
from neon_identity_provider_schema import _EXTRA
from neon_ai_budget_schema import _TABLES as _BUDGET
from neon_business_analytics_schema import _DATA
from neon_tenant_content_schema import _DDL
from neon_review_security_schema import _REVIEW
from neon_schema_inventory import inventory_sqlite_for_neon
from neon_inactive_migration_plan import _column_inventory

_SOURCE_TYPES = {"TEXT", "INTEGER", "BLOB"}
_TARGET_TYPES = {"TEXT", "SMALLINT", "INTEGER", "BIGINT", "BYTEA"}
_COLUMN = re.compile(
    r"(?<![a-z0-9_])([a-z][a-z0-9_]*)\s+"
    r"(TEXT|SMALLINT|INTEGER|BIGINT|BYTEA)\b", re.I)
_SHA = re.compile(r"[a-f0-9]{64}\Z")
_CATALOGS = (_BASE, _COLLAB, _EXTRA, _BUDGET, _DATA, _DDL, _REVIEW)


def _target_catalog():
    target = {}
    for catalog in _CATALOGS:
        for name, columns, ddl in catalog:
            if name in target or not ddl.startswith("CREATE TABLE " + name + " ("):
                raise ValueError("Target table preview is not independently parsable")
            found = [(match.group(1), match.group(2).upper())
                     for match in _COLUMN.finditer(ddl)]
            if ([name for name, _ in found] != list(columns)
                    or len(set(columns)) != len(columns)
                    or any(dtype not in _TARGET_TYPES for _, dtype in found)):
                raise ValueError("Unreviewed PostgreSQL target column declaration")
            target[name] = {"columns": found,
                            "generated_identity": "GENERATED BY DEFAULT AS IDENTITY" in ddl}
    if len(target) != 46:
        raise ValueError("Unexpected target table preview count")
    return target


def _proposal(source_type, target_type):
    if source_type == "TEXT" and target_type == "TEXT":
        return "text_encoding_collation_json_and_semantics_review"
    if source_type == "INTEGER" and target_type in ("SMALLINT", "INTEGER", "BIGINT"):
        return "integer_range_null_boolean_and_constraint_review"
    if source_type == "BLOB" and target_type == "BYTEA":
        return "blob_to_bytea_binary_adapter_review"
    return "unsupported_type_pair_manual_mapping_required"


def compile_offline_column_transform_review(db, *, pinned_source_sha256=None,
                                            pinned_mapping_sha256=None):
    """Report stable column/type proposals; all value transforms stay blocked."""
    if not isinstance(db, sqlite3.Connection):
        raise TypeError("Trusted offline SQLite connection required")
    for label, pin in (("source", pinned_source_sha256),
                       ("mapping", pinned_mapping_sha256)):
        if pin is not None and (
                type(pin) is not str or _SHA.fullmatch(pin) is None):
            raise ValueError("Invalid independent " + label + " SHA-256 pin")
    source = inventory_sqlite_for_neon(db)
    targets = _target_catalog()
    present = {entry["table"] for entry in source["tables"]}
    shape = []
    unsupported = []
    mismatched = []
    for name in sorted(targets):
        target = targets[name]
        expected = target["columns"]
        actual = _column_inventory(db, name) if name in present else []
        by_name = {col["name"]: col for col in actual}
        target_names = {col for col, _ in expected}
        proposals = []
        for column, pg_type in expected:
            local = by_name.get(column)
            source_type = local["sqlite_declared_type"] if local else None
            proposed = _proposal(source_type, pg_type)
            if proposed.startswith("unsupported"):
                unsupported.append(name + "." + column)
            proposals.append({
                "column": column, "source_type": source_type,
                "target_type": pg_type, "source_not_null":
                    local["not_null"] if local else None,
                "source_pk_position": local["pk_position"] if local else None,
                "source_has_default": local["has_default"] if local else None,
                "candidate_conversion": proposed,
                "value_transform_reviewed": False,
                "constraint_and_default_reviewed": False,
                "tenant_semantics_reviewed": False})
        extra = sorted(set(by_name) - target_names)
        if extra or not actual or len(actual) != len(expected):
            mismatched.append(name)
        shape.append({
            "source_table": name, "target_table": name,
            "source_table_present": bool(actual),
            "source_only_columns": extra,
            "identity_sequence_requires_reseed_review":
                target["generated_identity"],
            "columns": proposals, "independently_reviewed": False})
    source_digest = source["schema_digest"]
    shape_to_hash = {
        "format": "bam-offline-column-transform-review-v1",
        "source_schema_sha256": source_digest,
        "unreviewed_source_tables": source["unreviewed_pg_preview_table_names"],
        "mappings": shape}
    fingerprint = hashlib.sha256(json.dumps(
        shape_to_hash, sort_keys=True, separators=(",", ":"),
        ensure_ascii=True).encode("ascii")).hexdigest()
    blockers = [
        "all_value_transform_and_constraint_reviews_outstanding",
        "tenant_reference_and_identity_sequence_reviews_outstanding",
        "postgresql_transactional_runner_write_fence_rollback_disabled",
        "customer_data_export_and_production_cutover_disabled"]
    if unsupported:
        blockers.append("unsupported_source_target_type_pairs")
    if mismatched:
        blockers.append("source_target_column_shape_mismatch")
    if source["unreviewed_pg_preview_table_names"]:
        blockers.append("unreviewed_source_tables")
    if pinned_source_sha256 is None:
        blockers.append("independent_source_schema_pin_missing")
    elif pinned_source_sha256 != source_digest:
        blockers.append("independent_source_schema_pin_drift")
    if pinned_mapping_sha256 is None:
        blockers.append("independent_mapping_pin_missing")
    elif pinned_mapping_sha256 != fingerprint:
        blockers.append("independent_mapping_pin_drift")
    return {
        "status": "offline_column_transform_review_blocked",
        "format": shape_to_hash["format"],
        "source_schema_sha256": source_digest,
        "mapping_sha256": fingerprint,
        "source_pin_matches": pinned_source_sha256 == source_digest
            if pinned_source_sha256 is not None else False,
        "mapping_pin_matches": pinned_mapping_sha256 == fingerprint
            if pinned_mapping_sha256 is not None else False,
        "mapped_target_table_count": len(shape),
        "mapped_target_column_count": sum(len(row["columns"]) for row in shape),
        "unreviewed_source_tables": source["unreviewed_pg_preview_table_names"],
        "unsupported_type_pair_columns": unsupported,
        "column_shape_mismatch_tables": mismatched,
        "mappings": shape,
        "blockers": blockers,
        "all_columns_independently_approved": False,
        "postgres_connected": False, "customer_rows_read": False,
        "source_writes_performed": False, "rows_migrated": False,
        "write_fence_implemented": False, "rollback_executable": False,
        "cutover_permitted": False, "production_ready": False,
        "publishing_enabled": False}
